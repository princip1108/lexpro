CREATE OR REPLACE FUNCTION lexpro.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- -----------------------------------------------------------------------------
-- 1. Users and cases
-- -----------------------------------------------------------------------------

CREATE TABLE app_user (
    user_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username           varchar(100) NOT NULL,
    password_hash      varchar(255) NOT NULL,
    real_name          varchar(100) NOT NULL,
    role               varchar(30) NOT NULL DEFAULT 'USER',
    permissions_json   jsonb NOT NULL DEFAULT '{}'::jsonb,
    case_scope         jsonb NOT NULL DEFAULT '{}'::jsonb,
    status             varchar(20) NOT NULL DEFAULT 'ACTIVE',
    created_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_app_user_username_not_blank
        CHECK (btrim(username) <> ''),
    CONSTRAINT ck_app_user_password_hash_not_blank
        CHECK (btrim(password_hash) <> ''),
    CONSTRAINT ck_app_user_role
        CHECK (role IN ('ADMIN', 'USER')),
    CONSTRAINT ck_app_user_status
        CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT ck_app_user_permissions_object
        CHECK (jsonb_typeof(permissions_json) = 'object'),
    CONSTRAINT ck_app_user_case_scope_object
        CHECK (jsonb_typeof(case_scope) = 'object')
);

CREATE UNIQUE INDEX ux_app_user_username_lower
    ON app_user (lower(username));

CREATE TRIGGER trg_app_user_updated_at
BEFORE UPDATE ON app_user
FOR EACH ROW EXECUTE FUNCTION lexpro.set_updated_at();

CREATE TABLE case_record (
    case_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_name          varchar(255) NOT NULL,
    case_no            varchar(100),
    case_type          varchar(50) NOT NULL,
    case_cause         varchar(255),
    prosecutor_id      bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    creator_id         bigint NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT,
    accept_date        date,
    deadline_date      date,
    case_status        varchar(30) NOT NULL DEFAULT 'PENDING',
    created_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_case_record_name_not_blank
        CHECK (btrim(case_name) <> ''),
    CONSTRAINT ck_case_record_type_not_blank
        CHECK (btrim(case_type) <> ''),
    CONSTRAINT ck_case_record_status
        CHECK (case_status IN ('PENDING', 'PROCESSING', 'CLOSED', 'ARCHIVED')),
    CONSTRAINT ck_case_record_dates
        CHECK (deadline_date IS NULL OR accept_date IS NULL OR deadline_date >= accept_date)
);

CREATE UNIQUE INDEX ux_case_record_case_no
    ON case_record (case_no)
    WHERE case_no IS NOT NULL;

CREATE INDEX ix_case_record_creator_id ON case_record (creator_id);
CREATE INDEX ix_case_record_prosecutor_id ON case_record (prosecutor_id);
CREATE INDEX ix_case_record_status ON case_record (case_status);
CREATE INDEX ix_case_record_accept_date ON case_record (accept_date);

CREATE TRIGGER trg_case_record_updated_at
BEFORE UPDATE ON case_record
FOR EACH ROW EXECUTE FUNCTION lexpro.set_updated_at();

CREATE TABLE case_party (
    party_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id            bigint NOT NULL REFERENCES case_record(case_id) ON DELETE RESTRICT,
    party_name         varchar(255) NOT NULL,
    party_role         varchar(30) NOT NULL,
    party_type         varchar(30) NOT NULL,
    identity_type      varchar(30),
    identity_number    varchar(100),
    gender             varchar(20),
    age                integer,
    description        text,
    created_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_case_party_name_not_blank
        CHECK (btrim(party_name) <> ''),
    CONSTRAINT ck_case_party_role
        CHECK (party_role IN ('SUSPECT', 'VICTIM', 'WITNESS', 'OTHER')),
    CONSTRAINT ck_case_party_type
        CHECK (party_type IN ('PERSON', 'ORGANIZATION')),
    CONSTRAINT ck_case_party_age
