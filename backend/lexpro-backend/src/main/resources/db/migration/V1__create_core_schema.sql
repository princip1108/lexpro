-- 6. Audit log
-- -----------------------------------------------------------------------------

CREATE TABLE operation_log (
    log_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    case_id             bigint REFERENCES case_record(case_id) ON DELETE SET NULL,
    operation_type      varchar(50) NOT NULL,
    object_type         varchar(50),
    object_id           varchar(100),
    operation_result    varchar(30) NOT NULL,
    operation_time      timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    detail              jsonb,
    request_id          varchar(100),

    CONSTRAINT ck_operation_log_type_not_blank
        CHECK (btrim(operation_type) <> ''),
    CONSTRAINT ck_operation_log_result
        CHECK (operation_result IN ('SUCCESS', 'FAILED'))
);

CREATE INDEX ix_operation_log_user_time
    ON operation_log (user_id, operation_time DESC);
CREATE INDEX ix_operation_log_case_time
    ON operation_log (case_id, operation_time DESC);
CREATE INDEX ix_operation_log_request_id
    ON operation_log (request_id)
    WHERE request_id IS NOT NULL;

