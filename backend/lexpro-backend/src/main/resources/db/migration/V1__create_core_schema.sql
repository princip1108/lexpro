CREATE TABLE case_recommendation_item (
    item_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommend_id         bigint NOT NULL REFERENCES case_recommendation(recommend_id) ON DELETE CASCADE,
    typical_case_id      bigint NOT NULL REFERENCES typical_case(typical_case_id) ON DELETE RESTRICT,
    rank_no              integer NOT NULL,
    similarity_score     numeric(8,6),
    reason_json          jsonb,

    CONSTRAINT ux_case_recommendation_item_rank
        UNIQUE (recommend_id, rank_no),
    CONSTRAINT ux_case_recommendation_item_case
        UNIQUE (recommend_id, typical_case_id),
    CONSTRAINT ck_case_recommendation_item_rank
        CHECK (rank_no > 0),
    CONSTRAINT ck_case_recommendation_item_score
        CHECK (similarity_score IS NULL OR (similarity_score >= -1 AND similarity_score <= 1))
);

CREATE INDEX ix_case_recommendation_item_typical_case_id
    ON case_recommendation_item (typical_case_id);

