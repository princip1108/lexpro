CREATE TABLE case_card_fill_task (
    fill_task_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id             bigint NOT NULL REFERENCES case_record(case_id) ON DELETE RESTRICT,
    fill_mode           varchar(30) NOT NULL,
    fill_status         varchar(30) NOT NULL DEFAULT 'PENDING',
    operator_id         bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at        timestamptz,
    confirmed_by        bigint REFERENCES app_user(user_id) ON DELETE SET NULL,

    CONSTRAINT ck_case_card_fill_task_mode
        CHECK (fill_mode IN ('AUTO', 'MANUAL', 'HYBRID')),
    CONSTRAINT ck_case_card_fill_task_status
        CHECK (fill_status IN ('PENDING', 'PROCESSING', 'DRAFT', 'CONFIRMED', 'FAILED')),
    CONSTRAINT ck_case_card_fill_task_confirmed
        CHECK ((confirmed_by IS NULL) = (confirmed_at IS NULL)),
    CONSTRAINT ck_case_card_fill_task_confirmed_status
        CHECK (fill_status <> 'CONFIRMED' OR confirmed_at IS NOT NULL)
);

CREATE INDEX ix_case_card_fill_task_case_id ON case_card_fill_task (case_id);
CREATE INDEX ix_case_card_fill_task_operator_id ON case_card_fill_task (operator_id);
CREATE INDEX ix_case_card_fill_task_status ON case_card_fill_task (fill_status);

-- A source row must point to exactly one typed source. This avoids an
-- untyped source_result_id that cannot be protected by a foreign key.
CREATE TABLE case_card_task_source (
    source_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fill_task_id        bigint NOT NULL REFERENCES case_card_fill_task(fill_task_id) ON DELETE CASCADE,
    doc_id              bigint REFERENCES document_parse_result(doc_id) ON DELETE RESTRICT,
    entity_result_id    bigint REFERENCES entity_result(entity_result_id) ON DELETE RESTRICT,
    element_result_id   bigint REFERENCES legal_element_result(element_result_id) ON DELETE RESTRICT,
    summary_id          bigint REFERENCES case_summary(summary_id) ON DELETE RESTRICT,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_case_card_task_source_exactly_one
        CHECK (num_nonnulls(doc_id, entity_result_id, element_result_id, summary_id) = 1)
);

CREATE INDEX ix_case_card_task_source_fill_task_id
    ON case_card_task_source (fill_task_id);
CREATE UNIQUE INDEX ux_case_card_task_source_doc
    ON case_card_task_source (fill_task_id, doc_id) WHERE doc_id IS NOT NULL;
CREATE UNIQUE INDEX ux_case_card_task_source_entity
    ON case_card_task_source (fill_task_id, entity_result_id) WHERE entity_result_id IS NOT NULL;
CREATE UNIQUE INDEX ux_case_card_task_source_element
    ON case_card_task_source (fill_task_id, element_result_id) WHERE element_result_id IS NOT NULL;
CREATE UNIQUE INDEX ux_case_card_task_source_summary
    ON case_card_task_source (fill_task_id, summary_id) WHERE summary_id IS NOT NULL;

CREATE TABLE case_card_field (
    field_id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fill_task_id            bigint NOT NULL REFERENCES case_card_fill_task(fill_task_id) ON DELETE CASCADE,
    field_code              varchar(100) NOT NULL,
    field_name              varchar(255) NOT NULL,
    field_value             text,
    field_value_json        jsonb,
    source_text             text,
    source_file_id          bigint REFERENCES evidence_file(dossier_id) ON DELETE RESTRICT,
    source_location_json    jsonb,
    confidence              numeric(5,4),
    confirm_status          varchar(30) NOT NULL DEFAULT 'UNCONFIRMED',
    confirmed_by            bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    confirmed_at            timestamptz,

    CONSTRAINT ux_case_card_field_code
        UNIQUE (fill_task_id, field_code),
    CONSTRAINT ck_case_card_field_code_not_blank
        CHECK (btrim(field_code) <> ''),
    CONSTRAINT ck_case_card_field_name_not_blank
        CHECK (btrim(field_name) <> ''),
    CONSTRAINT ck_case_card_field_value
        CHECK (field_value IS NOT NULL OR field_value_json IS NOT NULL),
    CONSTRAINT ck_case_card_field_confidence
        CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1)),
    CONSTRAINT ck_case_card_field_confirm_status
        CHECK (confirm_status IN ('UNCONFIRMED', 'CONFIRMED', 'REJECTED')),
    CONSTRAINT ck_case_card_field_confirmed
        CHECK ((confirmed_by IS NULL) = (confirmed_at IS NULL)),
    CONSTRAINT ck_case_card_field_confirmed_status
        CHECK (confirm_status <> 'CONFIRMED' OR confirmed_at IS NOT NULL)
);

CREATE INDEX ix_case_card_field_fill_task_id ON case_card_field (fill_task_id);
CREATE INDEX ix_case_card_field_source_file_id ON case_card_field (source_file_id);
CREATE INDEX ix_case_card_field_confirm_status ON case_card_field (confirm_status);

