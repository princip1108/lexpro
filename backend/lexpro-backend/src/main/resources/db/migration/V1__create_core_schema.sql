CREATE TABLE case_report (
    report_id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id                 bigint NOT NULL REFERENCES case_record(case_id) ON DELETE RESTRICT,
    template_id             bigint REFERENCES report_template(template_id) ON DELETE SET NULL,
    card_fill_task_id       bigint REFERENCES case_card_fill_task(fill_task_id) ON DELETE SET NULL,
    version_no              integer NOT NULL,
    report_type             varchar(50) NOT NULL,
    generate_mode           varchar(30) NOT NULL,
    operator_id             bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    report_status           varchar(30) NOT NULL DEFAULT 'GENERATING',
    report_title            varchar(255) NOT NULL,
    report_content_json     jsonb,
    error_message           text,
    generated_at            timestamptz,
    updated_at              timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalized_at            timestamptz,
    finalized_by            bigint REFERENCES app_user(user_id) ON DELETE SET NULL,

    CONSTRAINT ux_case_report_version
        UNIQUE (case_id, report_type, version_no),
    CONSTRAINT ck_case_report_version
        CHECK (version_no > 0),
    CONSTRAINT ck_case_report_mode
        CHECK (generate_mode IN ('AUTO', 'MANUAL', 'HYBRID')),
    CONSTRAINT ck_case_report_status
        CHECK (report_status IN ('GENERATING', 'DRAFT', 'REVIEWING', 'FINAL', 'FAILED')),
    CONSTRAINT ck_case_report_title_not_blank
        CHECK (btrim(report_title) <> ''),
    CONSTRAINT ck_case_report_failed_error
        CHECK (report_status <> 'FAILED' OR error_message IS NOT NULL),
    CONSTRAINT ck_case_report_finalized
        CHECK ((finalized_by IS NULL) = (finalized_at IS NULL)),
    CONSTRAINT ck_case_report_final_status
        CHECK (report_status <> 'FINAL' OR finalized_at IS NOT NULL)
);

CREATE INDEX ix_case_report_case_id ON case_report (case_id);
CREATE INDEX ix_case_report_template_id ON case_report (template_id);
CREATE INDEX ix_case_report_card_fill_task_id ON case_report (card_fill_task_id);
CREATE INDEX ix_case_report_operator_id ON case_report (operator_id);
CREATE INDEX ix_case_report_status ON case_report (report_status);

CREATE TRIGGER trg_case_report_updated_at
BEFORE UPDATE ON case_report
FOR EACH ROW EXECUTE FUNCTION lexpro.set_updated_at();

CREATE TABLE report_evidence (
    report_id           bigint NOT NULL REFERENCES case_report(report_id) ON DELETE CASCADE,
    dossier_id          bigint NOT NULL REFERENCES evidence_file(dossier_id) ON DELETE RESTRICT,
