CREATE INDEX ix_case_party_case_id ON case_party (case_id);
CREATE INDEX ix_case_party_case_role ON case_party (case_id, party_role);

CREATE TRIGGER trg_case_party_updated_at
BEFORE UPDATE ON case_party
FOR EACH ROW EXECUTE FUNCTION lexpro.set_updated_at();

CREATE TABLE case_assignment (
    assignment_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id            bigint NOT NULL REFERENCES case_record(case_id) ON DELETE RESTRICT,
    user_id            bigint NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT,
    assignment_role    varchar(30) NOT NULL,
    is_current         boolean NOT NULL DEFAULT true,
    assigned_at        timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at           timestamptz,

    CONSTRAINT ck_case_assignment_role
        CHECK (assignment_role IN ('PROSECUTOR', 'ASSIGNEE', 'REVIEWER')),
    CONSTRAINT ck_case_assignment_period
        CHECK (ended_at IS NULL OR ended_at >= assigned_at),
    CONSTRAINT ck_case_assignment_current_end
        CHECK (NOT is_current OR ended_at IS NULL)
);

CREATE UNIQUE INDEX ux_case_assignment_current
    ON case_assignment (case_id, user_id, assignment_role)
    WHERE is_current;

CREATE INDEX ix_case_assignment_case_id ON case_assignment (case_id);
CREATE INDEX ix_case_assignment_user_id ON case_assignment (user_id);

