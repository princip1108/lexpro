CREATE TABLE evidence_file (
    dossier_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id            bigint NOT NULL REFERENCES case_record(case_id) ON DELETE RESTRICT,
    file_name          varchar(255) NOT NULL,
    file_type          varchar(100) NOT NULL,
    file_url           text NOT NULL,
    upload_user_id     bigint NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT,
    uploaded_at        timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    file_size          bigint,
    file_hash          varchar(128),
    parse_status       varchar(30) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT ck_evidence_file_name_not_blank
        CHECK (btrim(file_name) <> ''),
    CONSTRAINT ck_evidence_file_url_not_blank
        CHECK (btrim(file_url) <> ''),
    CONSTRAINT ck_evidence_file_size
        CHECK (file_size IS NULL OR file_size >= 0),
    CONSTRAINT ck_evidence_file_parse_status
        CHECK (parse_status IN ('PENDING', 'PROCESSING', 'SUCCESS', 'FAILED'))
);

CREATE INDEX ix_evidence_file_case_id ON evidence_file (case_id);
CREATE INDEX ix_evidence_file_upload_user_id ON evidence_file (upload_user_id);
CREATE INDEX ix_evidence_file_case_parse_status ON evidence_file (case_id, parse_status);
CREATE INDEX ix_evidence_file_case_hash ON evidence_file (case_id, file_hash)
    WHERE file_hash IS NOT NULL;

CREATE TABLE document_parse_result (
    doc_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dossier_id          bigint NOT NULL REFERENCES evidence_file(dossier_id) ON DELETE RESTRICT,
    version_no          integer NOT NULL,
    parse_status        varchar(30) NOT NULL DEFAULT 'PROCESSING',
    parsed_text_json    jsonb,
    raw_text            text,
    parser_version      varchar(100),
    error_message       text,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at        timestamptz,

    CONSTRAINT ux_document_parse_result_version
        UNIQUE (dossier_id, version_no),
    CONSTRAINT ck_document_parse_result_version
        CHECK (version_no > 0),
    CONSTRAINT ck_document_parse_result_status
        CHECK (parse_status IN ('PROCESSING', 'SUCCESS', 'FAILED')),
    CONSTRAINT ck_document_parse_result_completed_at
        CHECK (completed_at IS NULL OR completed_at >= created_at),
    CONSTRAINT ck_document_parse_result_success_content
        CHECK (parse_status <> 'SUCCESS' OR raw_text IS NOT NULL OR parsed_text_json IS NOT NULL),
    CONSTRAINT ck_document_parse_result_failed_error
        CHECK (parse_status <> 'FAILED' OR error_message IS NOT NULL)
);

CREATE INDEX ix_document_parse_result_dossier_id
    ON document_parse_result (dossier_id);
CREATE INDEX ix_document_parse_result_status
    ON document_parse_result (parse_status);

CREATE TABLE entity_result (
    entity_result_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id              bigint NOT NULL REFERENCES document_parse_result(doc_id) ON DELETE RESTRICT,
    entities_json       jsonb NOT NULL,
    model_name          varchar(100),
    model_version       varchar(100),
    prompt_version      varchar(100),
    schema_version      varchar(50),
    created_by          bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_entity_result_entities_array
        CHECK (jsonb_typeof(entities_json) IN ('array', 'object'))
);

CREATE INDEX ix_entity_result_doc_id ON entity_result (doc_id);
CREATE INDEX ix_entity_result_created_by ON entity_result (created_by);

CREATE TABLE legal_element_result (
    element_result_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id                  bigint NOT NULL REFERENCES document_parse_result(doc_id) ON DELETE RESTRICT,
    case_cause              varchar(255),
    raw_elements_json       jsonb NOT NULL,
    final_elements_json     jsonb,
    validation_report_json  jsonb,
    model_name              varchar(100),
    model_version           varchar(100),
    prompt_version          varchar(100),
    schema_version          varchar(50),
    created_by              bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    created_at              timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_by            bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    confirmed_at            timestamptz,

    CONSTRAINT ck_legal_element_result_raw_json
        CHECK (jsonb_typeof(raw_elements_json) IN ('array', 'object')),
    CONSTRAINT ck_legal_element_result_confirmed
        CHECK ((confirmed_by IS NULL) = (confirmed_at IS NULL))
);

CREATE INDEX ix_legal_element_result_doc_id ON legal_element_result (doc_id);
CREATE INDEX ix_legal_element_result_created_by ON legal_element_result (created_by);

CREATE TABLE case_summary (
    summary_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id             bigint NOT NULL REFERENCES case_record(case_id) ON DELETE RESTRICT,
    summary_type        varchar(30) NOT NULL,
    summary_text        text NOT NULL,
    model_name          varchar(100),
    model_version       varchar(100),
    prompt_version      varchar(100),
    is_current          boolean NOT NULL DEFAULT true,
    created_by          bigint REFERENCES app_user(user_id) ON DELETE SET NULL,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_case_summary_type
        CHECK (summary_type IN ('FACT', 'PROCESS', 'CONCLUSION', 'FULL')),
    CONSTRAINT ck_case_summary_text_not_blank
        CHECK (btrim(summary_text) <> '')
);

CREATE UNIQUE INDEX ux_case_summary_current
    ON case_summary (case_id, summary_type)
    WHERE is_current;

CREATE INDEX ix_case_summary_case_id ON case_summary (case_id);
CREATE INDEX ix_case_summary_created_by ON case_summary (created_by);

