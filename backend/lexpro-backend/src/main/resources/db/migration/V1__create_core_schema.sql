    PRIMARY KEY (report_id, dossier_id),
    CONSTRAINT ck_report_evidence_sort_no
        CHECK (sort_no IS NULL OR sort_no > 0)
);

CREATE INDEX ix_report_evidence_dossier_id ON report_evidence (dossier_id);

CREATE TABLE report_legal_element_result (
    report_id           bigint NOT NULL REFERENCES case_report(report_id) ON DELETE CASCADE,
    element_result_id   bigint NOT NULL REFERENCES legal_element_result(element_result_id) ON DELETE RESTRICT,

    PRIMARY KEY (report_id, element_result_id)
);

CREATE INDEX ix_report_legal_element_result_element_id
    ON report_legal_element_result (element_result_id);

